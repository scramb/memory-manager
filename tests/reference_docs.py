_ENV_NAME_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")

# Read somewhere in src/memory_manager, but deliberately excluded from
# docs/reference/config.md, with why.
_EXCLUDED_ENV_VARS: dict[str, str] = {
    "MEMORY_MANAGER_TOKEN": (
        "a suggested client-side env var name (clients.base.DEFAULT_TOKEN_ENV / "
        "cli.py's 'connect claude-code --token-env' default) - never read by this "
        "process's own environ, only written into another client's config"
    ),
    "MM_GIT_SHA": (
        "build-time image metadata baked in by the container build "
        "(__init__.__commit__) - Operational, not a config surface a client "
        "or operator sets"
    ),
    "MM_TEST_DATABASE_URL": (
        "a CI/dev convenience fallback read only by 'memory-manager eval', not "
        "public product config"
    ),
}


def _is_environ_expr(node: ast.AST) -> bool:
    return (isinstance(node, ast.Name) and node.id == "environ") or (
        isinstance(node, ast.Attribute) and node.attr == "environ"
    )


def _scan_env_vars_in_file(path: Path, found: dict[str, list[str]]) -> None:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            func = node.func
            if (
                isinstance(func, ast.Attribute)
                and func.attr == "get"
                and _is_environ_expr(func.value)
            ):
                if (
                    node.args
                    and isinstance(node.args[0], ast.Constant)
                    and isinstance(node.args[0].value, str)
                ):
                    found.setdefault(node.args[0].value, []).append(str(path))
                continue
            fname = (
                func.id
                if isinstance(func, ast.Name)
                else func.attr
                if isinstance(func, ast.Attribute)
                else None
            )
            if fname and (fname in ("_require", "_require_env") or fname.startswith("_parse_")):
                for arg in (*node.args, *(kw.value for kw in node.keywords)):
                    if (
                        isinstance(arg, ast.Constant)
                        and isinstance(arg.value, str)
                        and _ENV_NAME_RE.match(arg.value)
                    ):
                        found.setdefault(arg.value, []).append(str(path))
        elif isinstance(node, ast.Subscript) and _is_environ_expr(node.value):
            index = node.slice
            if isinstance(index, ast.Constant) and isinstance(index.value, str):
                found.setdefault(index.value, []).append(str(path))
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                if (
                    isinstance(target, ast.Name)
                    and (target.id.endswith("_ENV") or target.id.endswith("_ENV_VAR"))
                    and isinstance(node.value, ast.Constant)
                    and isinstance(node.value.value, str)
                ):
                    found.setdefault(node.value.value, []).append(str(path))


def scan_env_vars(src_root: Path) -> dict[str, list[str]]:
    """Every env var name `src_root/**/*.py` reads, mapped to the file(s) it is read
    in: `environ.get(...)`/`environ[...]` (plain or `os.environ`), `_require(environ,
    "X", ...)`, `_require_env("X")`, `_parse_*(environ, "X", ...)` (positional or
    `name="X"`), and `*_ENV`/`*_ENV_VAR` constant assignments."""
    found: dict[str, list[str]] = {}
    for path in sorted(src_root.rglob("*.py")):
        _scan_env_vars_in_file(path, found)
    return found


def _documented_env_vars(config_text: str) -> set[str]:
    return set(re.findall(r"`([A-Z][A-Z0-9_]*)`", config_text))


def check_config_drift(config_text: str, found: Mapping[str, Sequence[str]]) -> list[str]:
    """Every name `scan_env_vars` found that `config_text` does not document, and every
    name `config_text` documents that is no longer read anywhere - `_EXCLUDED_ENV_VARS`
    subtracted from the first set."""
    read_vars = set(found) - set(_EXCLUDED_ENV_VARS)
    documented = _documented_env_vars(config_text)
    problems: list[str] = []
    for name in sorted(read_vars - documented):
        problems.append(
            f"{name} is read in src/memory_manager ({', '.join(found[name])}) but missing "
            "from docs/reference/config.md"
        )
    for name in sorted(documented - read_vars):
        problems.append(
            f"{name} is documented in docs/reference/config.md but is not read anywhere "
            "in src/memory_manager (nor excluded in tests/reference_docs.py)"
        )
    return problems


# -- note-format.md drift ------------------------------------------------------------


def _note_format_expectations() -> list[tuple[str, str]]:
    from memory_manager import exporter as exporter_mod
    from memory_manager.vault import note as note_mod
    from memory_manager.vault import paths as paths_mod
    from memory_manager.vault import validate as validate_mod

    expectations: list[tuple[str, str]] = [
        ("validate.MAX_FILE_BYTES", str(validate_mod.MAX_FILE_BYTES)),
        ("validate._MAX_TITLE_CHARS", str(validate_mod._MAX_TITLE_CHARS)),
        ("validate._MAX_DESCRIPTION_CHARS", str(validate_mod._MAX_DESCRIPTION_CHARS)),
        ("validate._MAX_TAGS", str(validate_mod._MAX_TAGS)),
        ("validate._MAX_ALIASES", str(validate_mod._MAX_ALIASES)),
        ("validate._MAX_ALIAS_CHARS", str(validate_mod._MAX_ALIAS_CHARS)),
        ("validate._MAX_SOURCE_CHARS", str(validate_mod._MAX_SOURCE_CHARS)),
        ("validate._TAG_RE", validate_mod._TAG_RE.pattern),
        ("paths._MAX_PATH_CHARS", str(paths_mod._MAX_PATH_CHARS)),
        ("paths._MAX_SLUG_CHARS", str(paths_mod._MAX_SLUG_CHARS)),
        ("paths._NAMESPACE_RE", paths_mod._NAMESPACE_RE.pattern),
        ("paths._SLUG_RE", paths_mod._SLUG_RE.pattern),
    ]
    for note_type in validate_mod.NOTE_TYPES:
        expectations.append((f"validate.NOTE_TYPES:{note_type}", _code(note_type)))
    for field_name in sorted(note_mod._KNOWN_FIELDS):
        expectations.append((f"note field {field_name}", _code(field_name)))
    for field_name in exporter_mod.ManifestEntry.__dataclass_fields__:
        expectations.append((f"exporter.ManifestEntry.{field_name}", _code(field_name)))
    for field_name in exporter_mod.Manifest.__dataclass_fields__:
        expectations.append((f"exporter.Manifest.{field_name}", _code(field_name)))
    return expectations


def check_note_format_drift(note_format_text: str) -> list[str]:
    """Every constant/field `_note_format_expectations` names that does not appear
    verbatim in `note_format_text` - a changed limit, a renamed field, or a field never
    documented in the first place."""
    return [
        f"{label} ({expected!r}) not found in docs/reference/note-format.md"
        for label, expected in _note_format_expectations()
        if expected not in note_format_text
    ]


# -- main -----------------------------------------------------------------------------


def _reference_dir(root: Path) -> Path:
    return root / "docs" / "reference"


async def _generated_pages() -> dict[str, str]:
    return {_TOOLS_PAGE: await render_tools_md(), _CLI_PAGE: render_cli_md()}


def main(
    argv: Sequence[str] | None = None,
    *,
    root: Path | None = None,
    src_root: Path | None = None,
) -> int:
    """`uv run python tests/reference_docs.py [--check]`. `root`/`src_root` are
    injectable for tests only - the real CLI invocation always uses the repository
    this file lives in (`REPO_ROOT`); `src_root` defaults to `root/src/memory_manager`
    so a test can point `root` at a throwaway `docs/reference` copy while still
    scanning the real source tree for `check_config_drift`."""
    import asyncio

    root = root if root is not None else REPO_ROOT
    src_root = src_root if src_root is not None else root / "src" / "memory_manager"
    parser = argparse.ArgumentParser(prog="reference_docs")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 naming every stale generated page and every drift found, writing nothing",
    )
    args = parser.parse_args(argv)

    reference_dir = _reference_dir(root)
    generated = asyncio.run(_generated_pages())

    if not args.check:
        reference_dir.mkdir(parents=True, exist_ok=True)
        for page, content in generated.items():
            (reference_dir / page).write_text(content, encoding="utf-8")
        return 0

    problems: list[str] = []
    for page, content in generated.items():
        path = reference_dir / page
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            problems.append(f"docs/reference/{page} is stale; run `make reference-docs`")

    config_path = reference_dir / _CONFIG_PAGE
    if config_path.exists():
        found = scan_env_vars(src_root)
        config_text = config_path.read_text(encoding="utf-8")
        problems.extend(check_config_drift(config_text, found))
    else:
        problems.append(f"docs/reference/{_CONFIG_PAGE} does not exist")

    note_format_path = reference_dir / _NOTE_FORMAT_PAGE
    if note_format_path.exists():
        problems.extend(check_note_format_drift(note_format_path.read_text(encoding="utf-8")))
    else:
        problems.append(f"docs/reference/{_NOTE_FORMAT_PAGE} does not exist")

    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
