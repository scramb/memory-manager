@dataclass(frozen=True)
class _CliArg:
    flags: tuple[str, ...]  # empty for a positional
    metavar: str | None
    required: bool
    default: str | None  # already rendered, or None for "no default"/"not applicable"
    choices: tuple[str, ...] | None
    repeatable: bool
    help: str


@dataclass(frozen=True)
class _CliCommand:
    name: str
    help: str
    positionals: tuple[_CliArg, ...]
    options: tuple[_CliArg, ...]
    mutually_exclusive: tuple[tuple[str, ...], ...]
    subcommands: tuple[_CliCommand, ...]


def _default_repr(action: argparse.Action) -> str | None:
    if action.default is None or action.default is argparse.SUPPRESS:
        return None
    return (
        _code(json.dumps(action.default))
        if isinstance(action.default, bool | int | float | str)
        else _code(str(action.default))
    )


def _arg_from_action(action: argparse.Action, *, is_positional: bool) -> _CliArg:
    choices = tuple(str(choice) for choice in action.choices) if action.choices else None
    metavar = action.metavar if isinstance(action.metavar, str) else None
    if is_positional and metavar is None:
        metavar = action.dest
    return _CliArg(
        flags=() if is_positional else tuple(action.option_strings),
        metavar=metavar,
        required=bool(action.required) if not is_positional else True,
        default=_default_repr(action) if not is_positional else None,
        choices=choices,
        repeatable=action.nargs in ("*", "+") or type(action).__name__ == "_AppendAction",
        help=action.help or "",
    )


def _switch_arg(actions: Sequence[argparse.Action], default: object) -> _CliArg:
    flags = tuple(flag for act in actions for flag in act.option_strings)
    helps = [act.help for act in actions if act.help]
    return _CliArg(
        flags=flags,
        metavar=None,
        required=False,
        default=_code(json.dumps(default)) if isinstance(default, bool) else None,
        choices=None,
        repeatable=False,
        help=" / ".join(helps),
    )


def _flag_label(arg: _CliArg) -> str:
    flags = "/".join(arg.flags) if arg.flags else ""
    if not arg.metavar:
        return _code(flags)
    label = f"{flags} {arg.metavar}".strip() if flags else arg.metavar
    return _code(label)


def _walk_parser(parser: argparse.ArgumentParser, name: str, help_text: str) -> _CliCommand:
    actions = cast(list[argparse.Action], cast(Any, parser)._actions)
    groups = cast(list[Any], cast(Any, parser)._mutually_exclusive_groups)

    store_bool: dict[str, list[argparse.Action]] = {}
    for action in actions:
        if type(action).__name__ in ("_StoreTrueAction", "_StoreFalseAction"):
            store_bool.setdefault(action.dest, []).append(action)

    handled: set[int] = set()
    options: list[_CliArg] = []
    for dest, group_actions in store_bool.items():
        if len(group_actions) < 2:
            continue
        options.append(_switch_arg(group_actions, parser.get_default(dest)))
        handled.update(id(act) for act in group_actions)

    positionals: list[_CliArg] = []
    subparsers_action: Any | None = None
    for action in actions:
        if id(action) in handled:
            continue
        if type(action).__name__ in ("_HelpAction",):
            continue
        if type(action).__name__ == "_SubParsersAction":
            subparsers_action = action
            continue
        if not action.option_strings:
            positionals.append(_arg_from_action(action, is_positional=True))
        else:
            options.append(_arg_from_action(action, is_positional=False))

    mutually_exclusive: list[tuple[str, ...]] = []
    for group in groups:
        group_actions = cast(list[argparse.Action], group._group_actions)
        flags = tuple(sorted(act.option_strings[0] for act in group_actions if act.option_strings))
        if flags:
            mutually_exclusive.append(flags)

    subcommands: list[_CliCommand] = []
    if subparsers_action is not None:
        choices = cast(Mapping[str, argparse.ArgumentParser], subparsers_action.choices)
        choice_help = {act.dest: (act.help or "") for act in subparsers_action._choices_actions}
        for sub_name in sorted(choices):
            subcommands.append(
                _walk_parser(choices[sub_name], sub_name, choice_help.get(sub_name, ""))
            )

    return _CliCommand(
        name=name,
        help=help_text,
        positionals=tuple(positionals),
        options=tuple(sorted(options, key=lambda arg: arg.flags)),
        mutually_exclusive=tuple(mutually_exclusive),
        subcommands=tuple(subcommands),
    )


def _args_table(args: Sequence[_CliArg]) -> list[str]:
    if not args:
        return []
    lines = ["| Flag | Required | Default | Choices | Help |", "|---|---|---|---|---|"]
    for arg in args:
        choices = ", ".join(_code(choice) for choice in arg.choices) if arg.choices else "—"
        repeatable = " (repeatable)" if arg.repeatable else ""
        lines.append(
            f"| {_flag_label(arg)}{repeatable} | {'yes' if arg.required else 'no'} "
            f"| {arg.default or '—'} | {choices} | {_cell(arg.help)} |"
        )
    lines.append("")
    return lines


def _render_command(command: _CliCommand, depth: int) -> list[str]:
    heading = "#" * min(depth + 1, 6)
    lines = [f"{heading} `{command.name}`", ""]
    if command.help:
        lines.append(_cell(command.help))
        lines.append("")
    if command.positionals:
        lines.append("Positional arguments:")
        lines.append("")
        lines.extend(_args_table(command.positionals))
    if command.options:
        lines.append("Options:")
        lines.append("")
        lines.extend(_args_table(command.options))
    if command.mutually_exclusive:
        lines.append("Mutually exclusive:")
        lines.append("")
        for group in command.mutually_exclusive:
            lines.append("- " + " / ".join(_code(flag) for flag in group))
        lines.append("")
    for sub in command.subcommands:
        lines.extend(_render_command(sub, depth + 1))
    return lines


def _build_parser_without_vault_dir() -> argparse.ArgumentParser:
    """`cli._build_parser()`, with `VAULT_DIR` absent from the environment while it
    builds - `cli.py` reads it (`os.environ.get("VAULT_DIR")`) as three different
    flags' default at parser-build time (`cli.py` around `doctor`/`export`/`migrate
    git-to-postgres`), so this is what makes the rendered page the same regardless of
    whether the calling process happens to have `VAULT_DIR` set."""
    from memory_manager.cli import _build_parser

    had = "VAULT_DIR" in os.environ
    saved = os.environ.pop("VAULT_DIR", None)
    try:
        return _build_parser()
    finally:
        if had and saved is not None:
            os.environ["VAULT_DIR"] = saved


def render_cli_md() -> str:
    """The full text of `docs/reference/cli.md`: every command, subcommand, positional,
    option, mutually exclusive group and the exit-code/human-output rules."""
    parser = _build_parser_without_vault_dir()
    actions = cast(list[argparse.Action], cast(Any, parser)._actions)
    subparsers_action = cast(
        Any, next(action for action in actions if type(action).__name__ == "_SubParsersAction")
    )
    choices = cast(Mapping[str, argparse.ArgumentParser], subparsers_action.choices)
    choice_help = {act.dest: (act.help or "") for act in subparsers_action._choices_actions}

    lines: list[str] = [
        _GENERATED_HEADER,
        "",
        "# CLI reference",
        "",
        _STABLE_BANNER,
        "",
        "Commands and flags below are Stable. The exit-code distinction between `0` "
        "(success) and any non-zero value (failure) is Stable; which specific non-zero "
        "value a given failure returns is not, and is inconsistent across commands "
        "today. Human-readable output (as opposed to a command's own `--json` output, "
        "where one exists) is Operational, not Stable, and may be reworded freely.",
        "",
    ]
    for name in sorted(choices):
        command = _walk_parser(choices[name], name, choice_help.get(name, ""))
        lines.extend(_render_command(command, depth=1))

    return "\n".join(lines) + "\n"


