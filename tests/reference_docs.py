_ANNOTATION_ORDER = ("readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint")


async def _list_prompt_names() -> list[str]:
    """Every prompt the real server registers, listed in-process - the same pattern
    `compat.lint.list_server_tools` uses for tools, reusing its own `_inert_services()`
    rather than building a second inert `Services`."""
    services = _inert_services()
    names: list[str] = []
    async with Client(build_server(services)) as client:
        cursor: str | None = None
        while True:
            listing = await client.list_prompts(cursor=cursor)
            names.extend(prompt.name for prompt in listing.prompts)
            if listing.next_cursor is None:
                return sorted(names)
            cursor = listing.next_cursor


@dataclass(frozen=True)
class _SchemaRow:
    path: str
    type: str
    required: bool
    default: str | None  # already rendered, or None for "no default"


def _type_str(node: Mapping[str, Any]) -> str:
    if "enum" in node:
        values = ", ".join(_code(str(value)) for value in node["enum"])
        return f"one of {values}"
    if "anyOf" in node:
        return " | ".join(_type_str(branch) for branch in node["anyOf"])
    kind = node.get("type")
    if kind == "array":
        items = node.get("items")
        inner = _type_str(items) if isinstance(items, Mapping) else "any"
        return f"{inner}[]"
    if isinstance(kind, str):
        return kind
    return "any"


def _schema_rows(schema: Mapping[str, Any]) -> list[_SchemaRow]:
    rows: list[_SchemaRow] = []
    _walk_schema(schema, "", True, rows)
    return rows


def _walk_schema(
    node: Mapping[str, Any], path: str, required: bool, rows: list[_SchemaRow]
) -> None:
    if "properties" in node:
        child_required = set(node.get("required") or [])
        props = cast(Mapping[str, Mapping[str, Any]], node["properties"])
        for name in sorted(props):
            child_path = f"{path}.{name}" if path else name
            _walk_schema(props[name], child_path, name in child_required, rows)
        return
    if "items" in node and "anyOf" not in node:
        items = cast(Mapping[str, Any], node["items"])
        _walk_schema(items, f"{path}[]", True, rows)
        return
    default = _code(json.dumps(node["default"])) if "default" in node else None
    rows.append(_SchemaRow(path=path, type=_type_str(node), required=required, default=default))


def _rows_table(rows: list[_SchemaRow]) -> list[str]:
    if not rows:
        return ["(no fields)", ""]
    lines = ["| Field | Type | Required | Default |", "|---|---|---|---|"]
    for row in rows:
        lines.append(
            f"| {_code(row.path)} | {_cell(row.type)} | {'yes' if row.required else 'no'} "
            f"| {row.default or '—'} |"
        )
    lines.append("")
    return lines


async def render_tools_md() -> str:
    """The full text of `docs/reference/tools.md`: every tool's annotations, parameters
    and result fields (`contract_snapshot.build_snapshot`, the real schemas), its
    description (`compat.lint.list_server_tools`, wording not Stable), the registered
    prompt names, and the derived structured error kinds."""
    tools = await list_server_tools()
    snapshot = await build_snapshot()
    descriptions = {tool.name: tool.description or "" for tool in tools}
    prompts = await _list_prompt_names()

    lines: list[str] = [
        _GENERATED_HEADER,
        "",
        "# MCP tools reference",
        "",
        _STABLE_BANNER,
        "",
        "Every tool name, parameter, result field, annotation and structured error kind "
        "below is Stable; a tool's *description* (the prose) is not (ADR-0017) and may "
        "be reworded in any release.",
        "",
    ]

    entries = cast(Mapping[str, Mapping[str, Any]], snapshot["tools"])
    for name in sorted(entries):
        entry = entries[name]
        lines.append(f"## `{name}`")
        lines.append("")
        description = descriptions.get(name, "")
        if description:
            lines.append(_cell(description))
            lines.append("")
        lines.append("Annotations:")
        lines.append("")
        lines.append("| Annotation | Value |")
        lines.append("|---|---|")
        annotations = cast(Mapping[str, Any], entry.get("annotations", {}))
        for hint in _ANNOTATION_ORDER:
            if hint in annotations:
                lines.append(f"| `{hint}` | `{json.dumps(annotations[hint])}` |")
        lines.append("")
        lines.append("Parameters:")
        lines.append("")
        lines.extend(_rows_table(_schema_rows(cast(Mapping[str, Any], entry["input"]))))
        if "output" in entry:
            lines.append("Result fields:")
            lines.append("")
            lines.extend(_rows_table(_schema_rows(cast(Mapping[str, Any], entry["output"]))))

    lines.append("## Prompts")
    lines.append("")
    for prompt_name in prompts:
        lines.append(f"- `{prompt_name}` - name is Stable, wording is not (ADR-0017)")
    lines.append("")

    lines.append("## Structured error kinds")
    lines.append("")
    lines.append(
        "Every tool result's second content channel (`isError`) carries a structured "
        "error with an `error` field naming one of these kinds, plus whatever extra "
        "fields that kind carries below. `message` wording is never Stable (ADR-0017)."
    )
    lines.append("")
    lines.append("| Kind | Fields |")
    lines.append("|---|---|")
    for kind, fields in error_kinds().items():
        rendered = ", ".join(_code(field) for field in fields)
        lines.append(f"| `{kind}` | {rendered} |")
    lines.append("")

    return "\n".join(lines) + "\n"


