def _cell(text: str) -> str:
    """`text` safe to put inside one Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def _code(text: str) -> str:
    return f"`{text}`"


# -- Structured error kinds (#200, ADR-0017, docs/compatibility.md "Structured error
# kinds") -----------------------------------------------------------------------------

# One example instance per `storage.base.WriteError` subclass, used only to call its own
# `to_dict()` and read off the field names it carries - the values themselves never
# appear anywhere, only the keys. Keyed by class name so `error_kinds` can fail closed
# (below) on a subclass this dict has never seen, rather than silently describing 7 of 8.
_WRITE_ERROR_EXAMPLES: dict[str, Callable[[], WriteError]] = {
    "VersionConflict": lambda: VersionConflict(
        "personal/fact/example.md", "0" * 64, "---\nid: ...\n---\n"
    ),
    "WriteConflict": lambda: WriteConflict(
        "personal/fact/example.md",
        "personal/fact/example.conflict.md",
        "0" * 64,
        "---\nid: ...\n---\n",
    ),
    "NotFound": lambda: NotFound("personal/fact/example.md"),
    "EditMismatch": lambda: EditMismatch("personal/fact/example.md", 2),
    "InvalidNote": lambda: InvalidNote("personal/fact/example.md", "example reason"),
    "SecretRejected": lambda: SecretRejected("personal/fact/example.md", "example reason"),
    "BlocklistRejected": lambda: BlocklistRejected("personal/fact/example.md", "example-category"),
    "WriteFailed": lambda: WriteFailed("example reason"),
}

# The three read-path errors `mcp.errors.error_to_dict` maps by hand (fixed by name,
# the same three that module's own `isinstance` chain names - nothing on the Python
# side marks these as "the read-path errors" the way `WriteError` marks its own
# subclasses, so there is nothing to discover here, unlike the dict above).
_READ_PATH_ERROR_EXAMPLES: dict[str, Callable[[], Exception]] = {
    "PathRejected": lambda: PathRejected("example reason"),
    "NoteFormatError": lambda: NoteFormatError("example reason"),
    "NoteInvalid": lambda: NoteInvalid(()),
}


def _all_subclasses(cls: type[Any]) -> set[type[Any]]:
    result: set[type[Any]] = set()
    for sub in cls.__subclasses__():
        result.add(sub)
        result |= _all_subclasses(sub)
    return result


def error_kinds() -> dict[str, list[str]]:
    """Every structured error kind a tool result's `error` field can carry, mapped to
    its own field names (including `error`/`message`): every subclass of
    `storage.base.WriteError`, discovered by recursing `__subclasses__()` so a newly
    added one is picked up automatically, plus the three read-path errors above.

    Raises `ValueError` naming any `WriteError` subclass this module does not yet know
    how to build an example of - fail closed, the same "unknown branch raises" rule
    `tests/contract_snapshot.py`'s schema walk applies, rather than silently rendering
    a reference page one kind short.
    """
    discovered = {cls.__name__ for cls in _all_subclasses(WriteError)}
    unknown = sorted(discovered - set(_WRITE_ERROR_EXAMPLES))
    if unknown:
        raise ValueError(
            f"no example instance recipe for new WriteError subclass(es) {unknown} - "
            "teach tests/reference_docs.py's _WRITE_ERROR_EXAMPLES about it"
        )
    kinds: dict[str, list[str]] = {}
    for name, factory in _WRITE_ERROR_EXAMPLES.items():
        if name not in discovered:
            continue  # a recipe for a subclass that no longer exists - nothing to render
        kinds[name] = sorted(factory().to_dict())
    for name, read_factory in _READ_PATH_ERROR_EXAMPLES.items():
        kinds[name] = sorted(error_to_dict(read_factory()))
    return dict(sorted(kinds.items()))


